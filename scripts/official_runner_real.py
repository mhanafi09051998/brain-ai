def query_llm(prompt: str, system: str = None) -> str:
    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": prompt})

    payload = json.dumps({
        "model": "ag/gemini-3.7-flash-high",
        "messages": messages,
        "temperature": 0.0
    }).encode("utf-8")

    req = urllib.request.Request(
        ROUTER_URL,
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {ROUTER_KEY}"
        }
    )
    try:
        full_text = []
        with urllib.request.urlopen(req, timeout=30) as res:
            raw_body = res.read().decode("utf-8")
            for line in raw_body.split('\n'):
                line = line.strip()
                if line.startswith('data: ') and line != 'data: [DONE]':
                    try:
                        chunk = json.loads(line[6:])
                        delta = chunk.get("choices", [{}])[0].get("delta", {})
                        if "content" in delta and delta["content"]:
                            full_text.append(delta["content"])
                    except Exception:
                        pass
        return "".join(full_text).strip()
    except Exception as e:
        return f"ERROR: {str(e)}"

def run_safe_python(code: str) -> str:
    """Safely execute Python code generated by LLM, auto-inspecting all variables, functions, and expressions."""
    test_code = code
    lines = [l.rstrip() for l in code.strip().split('\n') if l.strip()]
    if lines and not lines[-1].startswith(('def', 'class', 'import', 'for', 'while', 'if', 'print', 'return', '#')):
        if '=' not in lines[-1]:
            lines[-1] = f"print({lines[-1]})"
            test_code = '\n'.join(lines)
    
    if "print(" not in test_code:
        vars = re.findall(r'^([a-zA-Z0-9_]+)\s*=', code, re.MULTILINE)
        funcs = re.findall(r'def\s+([a-zA-Z0-9_]+)\s*\(', code)
        for v in vars:
            test_code += f"\ntry:\n    print('{v}:', {v})\nexcept Exception:\n    pass"
        for f in funcs:
            test_code += f"\ntry:\n    print('{f}():', {f}())\nexcept Exception:\n    pass"

    try:
        res = subprocess.run(
            [sys.executable, "-c", test_code],
            capture_output=True,
            text=True,
            timeout=3.0
        )
        return (res.stdout + "\n" + res.stderr).strip()
    except Exception:
        return ""

