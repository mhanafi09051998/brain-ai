def query_llm(prompt: str, system: str = None) -> str:
    compressed_prompt = prompt
    if "def " in prompt or "class " in prompt or "import " in prompt:
        compressed_prompt = compress_ast_context(prompt)

    cache_key = get_cache_key(system, compressed_prompt)
    if cache_key in KV_CACHE:
        entry = KV_CACHE[cache_key]
        if time.time() - entry["ts"] < 120:
            return entry["val"]

    messages = []
    if system:
        messages.append({"role": "system", "content": system})
    messages.append({"role": "user", "content": compressed_prompt})

    payload = json.dumps({
        "model": "ag/gemini-3.7-flash-high",
        "messages": messages,
        "temperature": 0.0,
        "cache_control": {"type": "ephemeral"}
    }).encode("utf-8")

    req = urllib.request.Request(
        ROUTER_URL,
        data=payload,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {ROUTER_KEY}",
            "X-KV-Cache": "warm-prefix"
        }
    )
    try:
        full_text = []
        with urllib.request.urlopen(req, timeout=30) as res:
            raw_body = res.read().decode("utf-8")
            for line in raw_body.split('\n'):
                line = line.strip()
                if line.startswith('data: ') and line != 'data: [DONE]':
                    try:
                        chunk = json.loads(line[6:])
                        delta = chunk.get("choices", [{}])[0].get("delta", {})
                        if "content" in delta and delta["content"]:
                            full_text.append(delta["content"])
                    except Exception:
                        pass
        ans = "".join(full_text).strip()
        if ans and not ans.startswith("ERROR:"):
            KV_CACHE[cache_key] = {"val": ans, "ts": time.time()}
        return ans
    except Exception as e:
        return f"ERROR: {str(e)}"

def run_safe_python(code: str) -> str:
    """Safely execute Python code generated by LLM, extracting all variables and expressions."""
    harness = f"""
import sys, math
try:
    import sympy
except Exception:
    pass

_output_lines = []
_local_scope = {{}}

try:
    # Execute user code
    exec({repr(code)}, globals(), _local_scope)
    
    # Check common result variables
    for target in ['ans', 'count', 'res', 'result', 'total', 's', 'val', 'sol', 'out', 'N', 'k']:
        if target in _local_scope:
            _output_lines.append(f"{{target}}: {{_local_scope[target]}}")
            
    # Print all numerical locals
    for _k, _v in list(_local_scope.items()):
        if not _k.startswith('_') and isinstance(_v, (int, float, str, list, set, dict)):
            _output_lines.append(f"{{_k}} = {{_v}}")
except Exception as _e:
    _output_lines.append(f"ERROR: {{_e}}")

for line in _output_lines:
    print(line)
"""
    try:
        res = subprocess.run(
            [sys.executable, "-c", harness],
            capture_output=True,
            text=True,
            timeout=4.0
        )
        return (res.stdout + "\n" + res.stderr).strip()
    except Exception:
        return ""

